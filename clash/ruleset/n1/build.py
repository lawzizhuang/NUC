#!/usr/bin/env python3
"""Build reviewed Mihomo YAML snapshots from a local ACL4SSR checkout (no network).

Usage: python3 build.py /path/to/ACL4SSR
Only URL-REGEX is removed. Any unexpected rule type aborts before writing files.
"""
import json
from pathlib import Path
import subprocess
import sys

REVISION = "3024bf8b2c9db5bf8807c4595674be8bbc22bd86"
NAMES = ("ChinaMedia", "ProxyMedia", "Download")
ALLOWED = {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "IP-CIDR", "IP-CIDR6", "PROCESS-NAME"}


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    root = Path(sys.argv[1]).resolve()
    revision = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    if revision != REVISION:
        raise SystemExit("Unexpected revision: review upstream changes and update REVISION first")
    outputs = {}
    for name in NAMES:
        relative = f"Clash/{name}.list"
        # Read committed bytes, not potentially modified checkout content.
        text = subprocess.check_output(["git", "-C", str(root), "show", f"{REVISION}:{relative}"]).decode("utf-8-sig")
        rules, removed = [], 0
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            kind = line.split(",", 1)[0]
            if kind == "URL-REGEX":
                removed += 1
                continue
            if kind not in ALLOWED:
                raise SystemExit(f"Unexpected rule type in {name}: {kind!r}")
            rules.append(line)
        header = (
            f"# Derived from ACL4SSR/ACL4SSR {relative}\n"
            f"# Revision: {REVISION}\n"
            "# License: CC-BY-SA-4.0; https://github.com/ACL4SSR/ACL4SSR\n"
            f"# Modification: removed {removed} unsupported URL-REGEX rules; all other rules retained.\n"
            "# Generated by build.py; do not edit by hand.\n"
            "payload:\n"
        )
        outputs[name] = header + "".join(f"  - {json.dumps(rule, ensure_ascii=False)}\n" for rule in rules)
        print(f"{name}: retained={len(rules)} removed_URL_REGEX={removed}")
    for name, content in outputs.items():
        Path(__file__).with_name(name + ".yaml").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
